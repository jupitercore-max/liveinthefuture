import { createElement, useContext } from "react";
import { HatchContextReactContext } from "./hatch-context.js";

export function useHatchContext() {
  const hatchContext = useContext(HatchContextReactContext);
  if (hatchContext == null) {
    throw new Error("useHatchContext must be used inside a HatchContextProvider");
  }
  return hatchContext;
}

function joinClassNames(...classNames) {
  return classNames.filter((value) => typeof value === "string" && value.trim().length > 0).join(" ");
}

export function SpaceRoot({ children, className, style, ...rest }) {
  return createElement(
    "div",
    {
      ...rest,
      className: joinClassNames("hatch-space-root", className),
      style,
      "data-hatch-space-root": "true",
    },
    children
  );
}
